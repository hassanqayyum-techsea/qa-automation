import { chromium } from "playwright";
const BASE = "http://127.0.0.1:3100";
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 2 })).newPage();
await page.goto(`${BASE}/login`);
await page.waitForLoadState("networkidle").catch(() => {});
await page.getByLabel("Email").fill("owner@example.com");
await page.getByRole("textbox", { name: "Password" }).fill("correct horse battery");
await page.getByRole("button", { name: "Sign in" }).click();
await page.waitForURL(`${BASE}/`);
await page.goto(process.argv[2]);
await page.waitForLoadState("networkidle", { timeout: 8000 }).catch(() => {});
const desc = page.getByText("Every save and AI edit", { exact: false });
console.log("versions text count", await desc.count());
const card = desc.locator("xpath=ancestor::*[.//table][1]");
await card.scrollIntoViewIfNeeded();
await page.waitForTimeout(500);
await card.screenshot({ path: "shots/17-versions-card.png" });
const hist = page.getByRole("table", { name: "Run history" }).locator("xpath=ancestor::*[.//*[contains(@class,'rounded')]][1]");
console.log("history", await page.getByRole("table", { name: "Run history" }).count());
await browser.close();
